  override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?
  ) -> Bool {
    // Replace with a real key from https://console.cloud.google.com/apis/credentials
    // (Maps SDK for iOS must be enabled for the key's project).
    GMSServices.provideAPIKey("REPLACE_WITH_YOUR_MAPS_IOS_API_KEY")
